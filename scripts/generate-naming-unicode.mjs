import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";

const sources = [
  [
    "DerivedGeneralCategory-16.0.0.txt",
    "7676ab755a41ef82108460238569e60ad65c191ddafe61b36c6765ec1353f293",
  ],
  [
    "CaseFolding-16.0.0.txt",
    "6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb",
  ],
  [
    "DerivedAge-16.0.0.txt",
    "60caa81b99a4dfb0bc5d38440d323073e3f356f46f9ca7869da848cd0715408b",
  ],
];
const paths = process.argv
  .slice(2)
  .filter((argument) => argument !== "--check");
if (paths.length !== 3)
  throw new Error(
    "Pass pinned DerivedGeneralCategory.txt, CaseFolding.txt and DerivedAge.txt paths.",
  );
const bytes = await Promise.all(paths.map((path) => readFile(path)));
const hashes = {};
for (let index = 0; index < sources.length; index++) {
  const [name, expected] = sources[index];
  const hash = createHash("sha256").update(bytes[index]).digest("hex");
  if (hash !== expected)
    throw new Error(`Unexpected pinned Unicode bytes for ${name}.`);
  hashes[name] = hash;
}
const fullCaseFold = {};
for (const line of bytes[1].toString("utf8").split("\n")) {
  const [code, status, mapping] = line
    .split("#")[0]
    .split(";")
    .map((part) => part.trim());
  if (status === "C" || status === "F")
    fullCaseFold[String(Number.parseInt(code, 16))] = mapping
      .split(" ")
      .map((point) => String.fromCodePoint(Number.parseInt(point, 16)))
      .join("");
}
const intervals = [];
for (const line of bytes[2].toString("utf8").split("\n")) {
  const text = line.split("#")[0].trim();
  if (text === "") continue;
  const ends = text.split(";")[0].trim().split("..");
  intervals.push([
    Number.parseInt(ends[0], 16),
    Number.parseInt(ends.at(-1), 16),
  ]);
}
intervals.sort((left, right) => left[0] - right[0]);
const assignedRanges = [];
for (const [low, high] of intervals) {
  const previous = assignedRanges.at(-1);
  if (previous && low <= previous[1] + 1)
    previous[1] = Math.max(high, previous[1]);
  else assignedRanges.push([low, high]);
}
const categories = {
  upper: [],
  lower: [],
  letter: [],
  mark: [],
  number: [],
  forbidden: [],
};
for (const line of bytes[0].toString("utf8").split("\n")) {
  const text = line.split("#")[0].trim();
  if (text === "") continue;
  const [interval, category] = text.split(";").map((part) => part.trim());
  const ends = interval.split("..");
  const range = [
    Number.parseInt(ends[0], 16),
    Number.parseInt(ends.at(-1), 16),
  ];
  if (category === "Lu" || category === "Lt") categories.upper.push(range);
  if (category === "Ll") categories.lower.push(range);
  if (category.startsWith("L")) categories.letter.push(range);
  if (category.startsWith("M")) categories.mark.push(range);
  if (category.startsWith("N")) categories.number.push(range);
  if (category === "Cc" || category === "Cf") categories.forbidden.push(range);
}
for (const ranges of Object.values(categories))
  ranges.sort((left, right) => left[0] - right[0]);
const source = `/* Unicode 16.0.0 data. Copyright Unicode, Inc. Unicode-3.0 license.\n * https://www.unicode.org/license.txt\n * Generated by scripts/generate-naming-unicode.mjs from Unicode 16 UCD sources.\n */\nexport const unicodeSourceHashes = ${JSON.stringify(hashes)};\nexport const fullCaseFold: Readonly<Record<string, string>> = ${JSON.stringify(fullCaseFold)};\nexport const assignedRanges: readonly (readonly [number, number])[] = ${JSON.stringify(assignedRanges)};\nexport const categoryRanges: Readonly<Record<"upper" | "lower" | "letter" | "mark" | "number" | "forbidden", readonly (readonly [number, number])[]>> = ${JSON.stringify(categories)};\n`;
const formatted = execFileSync(
  "./node_modules/.bin/biome",
  ["format", "--stdin-file-path=unicode-16.ts"],
  { input: source, encoding: "utf8" },
);
const destination = new URL(
  "../src/naming/generated/unicode-16.ts",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== formatted)
    throw new Error("Generated Unicode naming data drifted.");
} else await writeFile(destination, formatted);
