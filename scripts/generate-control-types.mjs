import { execFileSync } from "node:child_process";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { isDeepStrictEqual } from "node:util";
import { compile } from "json-schema-to-typescript";

const groups = [];
const schemaExports = {
  controls: "controlSchemas",
  naming: "namingSchemas",
  "controls-publication": "publicationSchemas",
  "migration/native-inventory": "nativeInventorySchemas",
};
for (const owner of Object.keys(schemaExports)) {
  const schemaRoot = new URL(`../src/${owner}/schemas/`, import.meta.url);
  const schemas = [];
  for (const name of (await readdir(schemaRoot)).sort())
    schemas.push({
      name,
      schema: JSON.parse(await readFile(new URL(name, schemaRoot), "utf8")),
    });
  groups.push({ owner, schemas });
}
groups.push({
  owner: "module-activity",
  schemas: [
    {
      name: "workflow.schema.json",
      schema: JSON.parse(
        await readFile(
          new URL(
            "../src/module-activity/workflow.schema.json",
            import.meta.url,
          ),
          "utf8",
        ),
      ),
    },
  ],
});
schemaExports["module-activity"] = "activitySchemas";
const registry = new Map(
  groups.flatMap(({ schemas }) =>
    schemas.map(({ schema }) => [schema.$id, schema]),
  ),
);
const activity = registry.get("urn:academic-os:module-activity:1");
const publication = registry.get("urn:academic-os:publication-contract:1");
const data = registry.get("urn:academic-os:module-data:1");
const generation = registry.get("urn:academic-os:control-generation:2");
const projection = {
  candidateId: publication.definitions.PublishWireInput.properties.candidateId,
  requestId: publication.definitions.PublishWireInput.properties.requestId,
  ControlRole: generation.properties.controls.items.properties.role,
  FrozenBytes: publication.definitions.FrozenBytes,
  ByteBinding: publication.definitions.ByteBinding,
  Refused: publication.definitions.Refused,
  RecoveryRequired: publication.definitions.RecoveryRequired,
};
for (const name of ["candidateId", "requestId"])
  if (
    !isDeepStrictEqual(
      publication.definitions.PublishWireInput.properties[name],
      publication.definitions.InspectWireInput.properties[name] ??
        publication.definitions.PublishWireInput.properties[name],
    )
  )
    throw new Error(
      `Publication ${name} grammar differs between inspect and publish.`,
    );
for (const name of ["target", "dateClaim", "evidenceReferences"]) {
  const value = structuredClone(data.definitions[name]);
  rewriteDataReferences(value);
  projection[`Data${name[0].toUpperCase()}${name.slice(1)}`] = value;
}
let projectionChanged = false;
for (const [name, value] of Object.entries(projection)) {
  projectionChanged ||= !isDeepStrictEqual(activity.definitions[name], value);
  activity.definitions[name] = structuredClone(value);
}
if (projectionChanged) {
  if (process.argv.includes("--check"))
    throw new Error(
      "Module activity schema projections drifted. Run npm run controls:generate.",
    );
  const formatted = execFileSync(
    "./node_modules/.bin/biome",
    ["format", "--stdin-file-path=workflow.schema.json"],
    { input: JSON.stringify(activity), encoding: "utf8" },
  );
  await writeFile(
    new URL("../src/module-activity/workflow.schema.json", import.meta.url),
    formatted,
  );
}

function rewriteDataReferences(value) {
  if (!value || typeof value !== "object") return;
  if (
    typeof value.$ref === "string" &&
    value.$ref.startsWith("#/definitions/")
  ) {
    const name = value.$ref.slice("#/definitions/".length);
    value.$ref = `#/definitions/Data${name[0].toUpperCase()}${name.slice(1)}`;
  }
  for (const child of Object.values(value)) rewriteDataReferences(child);
}
for (const { owner, schemas } of groups) {
  for (const { name, schema } of schemas)
    await emit(
      owner,
      `${name.replace(".schema.json", "")}.d.ts`,
      await compile(typeInput(owner, schema), schema.title, {
        bannerComment: "/* Generated by scripts/generate-control-types.mjs. */",
        additionalProperties: false,
        unknownAny: true,
        unreachableDefinitions:
          owner === "controls-publication" || owner === "module-activity",
        style: { singleQuote: false },
        $refOptions: {
          resolve: {
            file: false,
            http: false,
            registry: {
              order: 1,
              canRead: /^urn:academic-os:/u,
              read: ({ url }) => {
                const referenced = registry.get(url);
                if (referenced === undefined)
                  throw new Error(`Unknown schema ${url}.`);
                return owner === "naming"
                  ? referenced
                  : structuredClone(referenced);
              },
            },
          },
        },
      }),
    );
  await emit(
    owner,
    "schemas.ts",
    `/* Generated by scripts/generate-control-types.mjs. */\nexport const ${schemaExports[owner]} = ${JSON.stringify(schemas.map(({ schema }) => schema))};\n`,
  );
}

function typeInput(owner, schema) {
  const input = owner === "naming" ? schema : structuredClone(schema);
  if (schema.$id === "urn:academic-os:native-source-contract:1") {
    input.definitions.HostFailure.oneOf = ["Refused", "RecoveryRequired"].map(
      (name) => {
        const projected = `HostPublication${name}`;
        input.definitions[projected] = structuredClone(
          publication.definitions[name],
        );
        return { $ref: `#/definitions/${projected}` };
      },
    );
  }
  return input;
}

async function emit(owner, name, source) {
  const formatted = execFileSync(
    "./node_modules/.bin/biome",
    ["format", `--stdin-file-path=${name}`],
    { input: source, encoding: "utf8" },
  );
  const destination = new URL(
    `../src/${owner}/generated/${name}`,
    import.meta.url,
  );
  if (process.argv.includes("--check")) {
    if ((await readFile(destination, "utf8")) !== formatted)
      throw new Error(
        `Generated ${owner} types drifted: ${name}. Run npm run controls:generate.`,
      );
  } else await writeFile(destination, formatted);
}
