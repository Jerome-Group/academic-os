import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const schema = JSON.parse(
  await readFile(
    new URL(
      "../src/config/schemas/configuration-1.schema.json",
      import.meta.url,
    ),
    "utf8",
  ),
);
const generatedRoot = new URL("../src/config/generated/", import.meta.url);
for (const [name, source] of [
  [
    "configuration-1.d.ts",
    await compile(schema, schema.title, {
      bannerComment: "/* Generated by scripts/generate-config-types.mjs. */",
      additionalProperties: false,
      unknownAny: true,
      style: { singleQuote: false },
    }),
  ],
  [
    "schema.ts",
    `/* Generated by scripts/generate-config-types.mjs. */\nexport const configurationSchema = ${JSON.stringify(schema)};\n`,
  ],
]) {
  const formatted = execFileSync(
    "./node_modules/.bin/biome",
    ["format", `--stdin-file-path=${name}`],
    { input: source, encoding: "utf8" },
  );
  const destination = new URL(name, generatedRoot);
  if (process.argv.includes("--check")) {
    if ((await readFile(destination, "utf8")) !== formatted)
      throw new Error(
        `Generated configuration types drifted: ${name}. Run npm run config:generate.`,
      );
  } else await writeFile(destination, formatted);
}
