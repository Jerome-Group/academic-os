function localProjection(schema) {
  const definitions = {};
  const added = new Map();
  function rewrite(value, owner) {
    if (Array.isArray(value)) return value.map((item) => rewrite(item, owner));
    if (value === null || typeof value !== "object") return value;
    if (typeof value.$ref === "string") {
      const [document, pointer] = value.$ref.split("#");
      const id = document || owner;
      const source = registry.get(id);
      if (!source || !pointer?.startsWith("/definitions/"))
        throw new Error(`Unsupported projection reference ${value.$ref}.`);
      const name = pointer.slice("/definitions/".length);
      const key = `${id}#${pointer}`;
      let local = added.get(key);
      if (!local) {
        local =
          id === schema.$id
            ? name
            : `${id.replace("urn:academic-os:", "").replaceAll(/[^A-Za-z0-9]/gu, "_")}_${name}`;
        added.set(key, local);
        definitions[local] = {};
        const target = source.definitions[name];
        if (!target) throw new Error(`Missing projection reference ${key}.`);
        definitions[local] = rewrite(target, id);
      }
      return { $ref: `#/definitions/${local}` };
    }
    return Object.fromEntries(
      Object.entries(value)
        .filter(
          ([key, child]) =>
            key !== "definitions" &&
            !(["$id", "$schema"].includes(key) && typeof child === "string"),
        )
        .map(([key, child]) => [key, rewrite(child, owner)]),
    );
  }
  const body = rewrite(schema, schema.$id);
  for (const name of Object.keys(schema.definitions))
    rewrite({ $ref: `#/definitions/${name}` }, schema.$id);
  if (schema.$id === verification.$id)
    return {
      $schema: schema.$schema,
      title: "ModuleVerificationProjection",
      type: "object",
      additionalProperties: false,
      required: ["root"],
      properties: {
        root: body,
        ...Object.fromEntries(
          Object.keys(schema.definitions).map((name) => [
            name,
            { $ref: `#/definitions/${name}` },
          ]),
        ),
      },
      definitions,
    };
  return { $schema: schema.$schema, ...body, definitions };
}

async function emit(owner, name, source) {
  const formatted = execFileSync(
    "./node_modules/.bin/biome",
    ["format", `--stdin-file-path=${name}`],
    { input: source, encoding: "utf8" },
  );
  const destination = new URL(
    `../src/${owner}/generated/${name}`,
    import.meta.url,
  );
  if (process.argv.includes("--check")) {
    if ((await readFile(destination, "utf8")) !== formatted)
      throw new Error(
        `Generated ${owner} types drifted: ${name}. Run npm run controls:generate.`,
      );
  } else await writeFile(destination, formatted);
}
