import { readFile, readdir, writeFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { compile } from "json-schema-to-typescript";

const schemaRoot = new URL("../src/controls/schemas/", import.meta.url);
const generatedRoot = new URL("../src/controls/generated/", import.meta.url);
const schemas = [];
for (const name of (await readdir(schemaRoot)).sort()) {
  const schema = JSON.parse(await readFile(new URL(name, schemaRoot), "utf8"));
  schemas.push(schema);
  await emit(
    `${name.replace(".schema.json", "")}.d.ts`,
    await compile(schema, schema.title, {
      bannerComment: "/* Generated by scripts/generate-control-types.mjs. */",
      additionalProperties: false,
      unknownAny: true,
      style: { singleQuote: false },
    }),
  );
}
await emit(
  "schemas.ts",
  `/* Generated by scripts/generate-control-types.mjs. */\nexport const controlSchemas = ${JSON.stringify(schemas)};\n`,
);

async function emit(name, source) {
  const formatted = execFileSync(
    "./node_modules/.bin/biome",
    ["format", `--stdin-file-path=${name}`],
    { input: source, encoding: "utf8" },
  );
  const destination = new URL(name, generatedRoot);
  if (process.argv.includes("--check")) {
    if ((await readFile(destination, "utf8")) !== formatted)
      throw new Error(
        `Generated control types drifted: ${name}. Run npm run controls:generate.`,
      );
  } else await writeFile(destination, formatted);
}
