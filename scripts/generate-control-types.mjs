function rewriteDataReferences(value) {
  if (!value || typeof value !== "object") return;
  if (
    typeof value.$ref === "string" &&
    value.$ref.startsWith("#/definitions/")
  ) {
    const name = value.$ref.slice("#/definitions/".length);
    value.$ref = `#/definitions/Data${name[0].toUpperCase()}${name.slice(1)}`;
  }
  for (const child of Object.values(value)) rewriteDataReferences(child);
}
