import { execFileSync } from "node:child_process";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const groups = [];
const schemaExports = {
  controls: "controlSchemas",
  naming: "namingSchemas",
  "controls-publication": "publicationSchemas",
};
for (const owner of Object.keys(schemaExports)) {
  const schemaRoot = new URL(`../src/${owner}/schemas/`, import.meta.url);
  const schemas = [];
  for (const name of (await readdir(schemaRoot)).sort())
    schemas.push({
      name,
      schema: JSON.parse(await readFile(new URL(name, schemaRoot), "utf8")),
    });
  groups.push({ owner, schemas });
}
const registry = new Map(
  groups.flatMap(({ schemas }) =>
    schemas.map(({ schema }) => [schema.$id, schema]),
  ),
);
for (const { owner, schemas } of groups) {
  for (const { name, schema } of schemas)
    await emit(
      owner,
      `${name.replace(".schema.json", "")}.d.ts`,
      await compile(schema, schema.title, {
        bannerComment: "/* Generated by scripts/generate-control-types.mjs. */",
        additionalProperties: false,
        unknownAny: true,
        unreachableDefinitions: owner === "controls-publication",
        style: { singleQuote: false },
        $refOptions: {
          resolve: {
            file: false,
            http: false,
            registry: {
              order: 1,
              canRead: /^urn:academic-os:/u,
              read: ({ url }) => {
                const referenced = registry.get(url);
                if (referenced === undefined)
                  throw new Error(`Unknown schema ${url}.`);
                return owner === "controls-publication"
                  ? structuredClone(referenced)
                  : referenced;
              },
            },
          },
        },
      }),
    );
  await emit(
    owner,
    "schemas.ts",
    `/* Generated by scripts/generate-control-types.mjs. */\nexport const ${schemaExports[owner]} = ${JSON.stringify(schemas.map(({ schema }) => schema))};\n`,
  );
}

async function emit(owner, name, source) {
  const formatted = execFileSync(
    "./node_modules/.bin/biome",
    ["format", `--stdin-file-path=${name}`],
    { input: source, encoding: "utf8" },
  );
  const destination = new URL(
    `../src/${owner}/generated/${name}`,
    import.meta.url,
  );
  if (process.argv.includes("--check")) {
    if ((await readFile(destination, "utf8")) !== formatted)
      throw new Error(
        `Generated ${owner} types drifted: ${name}. Run npm run controls:generate.`,
      );
  } else await writeFile(destination, formatted);
}
